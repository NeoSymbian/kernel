"""Rasterise DejaVu Sans Mono (Bitstream Vera / DejaVu license) into a C header of 1-bit glyphs, ASCII 32-126.

Usage: python3 mkfont.py OUT.h [TTF] [CELL_W] [CELL_H]
Each glyph is CELL_H rows of a CELL_W-bit (<= 32) row word, MSB = leftmost pixel.
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

out = Path(sys.argv[1])
ttf = (
    sys.argv[2]
    if len(sys.argv) > 2
    else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
)
cw = int(sys.argv[3]) if len(sys.argv) > 3 else 16
ch = int(sys.argv[4]) if len(sys.argv) > 4 else 32
assert cw <= 32
font = ImageFont.truetype(ttf, size=int(ch * 0.8))
ascent, _ = font.getmetrics()
rows = []
for code in range(32, 127):
    img = Image.new("1", (cw, ch), 0)
    ImageDraw.Draw(img).text(
        (0, (ch - int(ch * 0.8)) // 2 + int(ch * 0.8) - ascent),
        chr(code),
        font=font,
        fill=1,
    )
    px = img.load()
    glyph = [sum(1 << (31 - x) for x in range(cw) if px[x, y]) for y in range(ch)]
    assert code != 65 or any(glyph), (
        "glyph 'A' rendered empty"
    )  # self-check: the font actually drew
    rows.append(glyph)
with out.open("w") as f:
    f.write(
        f"// generated by mkfont.py from {Path(ttf).name} (DejaVu fonts license) -- do not edit\n"
    )
    f.write(
        f"#define FONT_W {cw}\n#define FONT_H {ch}\n#define FONT_FIRST 32\n#define FONT_LAST 126\n"
    )
    f.write("static const unsigned int KFont[95][FONT_H] = {\n")
    for g in rows:
        f.write("{" + ",".join(f"0x{v:08x}" for v in g) + "},\n")
    f.write("};\n")
print(f"{out}: {len(rows)} glyphs {cw}x{ch}")
